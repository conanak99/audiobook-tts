def trim_point(path, limit):
    """Where to end a clip at most `limit` s long: inside the last pause before the limit, else at it."""
    total = seconds_of(path)
    if total <= limit:
        return total
    best = None
    for start, end in silences(path, -40, 0.12):
        end = end if end is not None else total
        if limit * 0.6 <= start <= limit:
            best = min(limit, (start + end) / 2)
    return round(best or limit, 2)


# --- cut ---------------------------------------------------------------------------------------------------
def cmd_cut(args):
    """Cut one or more windows into reference-1.wav, reference-2.wav, ... (<= 30 s together)."""
    vid = slugify(args.id)
    work = WORK / vid
    info = (
        json.loads((work / 'candidates.json').read_text(encoding='utf-8'))
        if (work / 'candidates.json').is_file()
        else {}
    )
    picks = []
    if args.candidate:
        for n in args.candidate:
            cand = next((c for c in info.get('candidates', []) if c['n'] == n), None)
            if not cand:
                raise SystemExit(f'No candidate {n}; run candidates first.')
            picks.append(
                dict(
                    cut_at=cand['cut_at'],
                    source_time=cand['source_time'],
                    duration=cand['duration'],
                    preview=ROOT / cand['file'],
                )
            )
    else:
        cut_at = parse_time(args.start)
        if cut_at is None or not args.duration:
            raise SystemExit('Give --candidate N [--candidate M], or --start and --duration (source-file times).')
        picks.append(dict(cut_at=cut_at, source_time=cut_at, duration=args.duration, preview=None))
    if len(picks) > 4:
        raise SystemExit('At most 4 references.')
    media = Path(args.media).expanduser().resolve() if args.media else Path(info.get('source', ''))
    if not media.is_file():
        raise SystemExit('Source media not found; pass --media.')
    url = info.get('url') if not args.media else None
    total = sum(p['duration'] for p in picks)
    if total > args.max_total:  # share the budget, ending each clip inside a natural pause
        for p in picks:
            share = args.max_total * p['duration'] / total
            p['duration'] = trim_point(p['preview'], share) if p['preview'] else round(share, 2)
    d = voice_dir(vid)
    d.mkdir(parents=True, exist_ok=True)
    # A new cut replaces the old references and their review scratch.
    for old in [*d.glob('reference*'), *work.glob('stt-*.json'), *work.glob('reference-*.draft.txt')]:
        old.unlink()
    refs = []
    for n, p in enumerate(picks, 1):
        ref = d / f'reference-{n}.wav'
        ffmpeg(
            '-ss',
            str(p['cut_at']),
            '-t',
            str(p['duration']),
            '-i',
            str(media),
            '-ac',
            '1',
            '-ar',
            '48000',
            '-af',
            CLEAN + ',afade=t=in:d=0.02,areverse,afade=t=in:d=0.03,areverse',
            '-c:a',
            'pcm_s16le',
            str(ref),
        )
        gain, _, _ = level(ref)
        refs.append(
            dict(
                n=n,
                file=ref.name,
                source_start=round(p['source_time'], 2),
                transcript_reviewed=False,
                gain_db=gain,
                **measure(ref),
            )
        )
    meta = json.loads((d / 'voice.json').read_text(encoding='utf-8')) if (d / 'voice.json').is_file() else {}
    meta.update(
        id=vid,
        status='draft',
        transcript_reviewed=False,
        source=dict(input=url or str(media)),
        references=refs,
        samples=[],
        metrics=dict(
            duration=round(sum(r['duration'] for r in refs), 2), longest_pause=max(r['longest_pause'] for r in refs)
        ),
    )
    meta.setdefault('name', args.id)
    save(meta)
    for r in refs:
        warn = []
        if r['duration'] < 10:
            warn.append('under 10 s (Fish recommends 15-20 s per clip)')
        if r['longest_pause'] > 0.8:
            warn.append(f'a {r["longest_pause"]}s pause (Drama-3 copies long pauses)')
        if r['speech_pct'] < 70:
            warn.append(f'only {r["speech_pct"]}% speech')
        if r['lufs'] is not None and r['lufs'] < TARGET_LUFS - 1:
            warn.append(f'{r["lufs"]} LUFS after leveling: the peak ceiling limited the gain (spiky source)')
        print(
            f'reference-{r["n"]}.wav  from {clock(r["source_start"])}  {r["duration"]}s  speech {r["speech_pct"]}%  '
            f'pause ≤{r["longest_pause"]}s  {r["lufs"]} LUFS ({r["gain_db"]:+.1f} dB)'
            + ''.join(f'\n  warning: {w}' for w in warn)
        )
    print(
        f'{len(refs)} reference(s), {meta["metrics"]["duration"]}s total. Next: python3 -m viettts voice transcribe {vid}'
    )


# --- level -------------------------------------------------------------------------------------------------
def cmd_level(args):
    """Match existing references to TARGET_LUFS (the cut step already does this for new ones)."""
    ids = [v['id'] for v in all_voices()] if args.all else [slugify(i) for i in args.ids]
    if not ids:
        raise SystemExit('Give voice ids or --all.')
    for vid in ids:
        meta = load(vid)
        changed = False
        for ref in meta.get('references', []):
            path = voice_dir(vid) / ref['file']
            if args.dry_run:
                lufs, peak = loudness(path)
                gain = level_gain(lufs, peak)
                print(f'{vid}/{ref["file"]}  {lufs} LUFS  peak {peak} dBTP  -> would add {gain:+.1f} dB')
                continue
            gain, before, after = level(path)
            if gain:
                ref.update(measure(path), gain_db=round(ref.get('gain_db', 0) + gain, 2))
                changed = True
            print(f'{vid}/{ref["file"]}  {before} -> {after} LUFS  ({gain:+.1f} dB)')
        if changed:
            save(meta)
            if meta.get('samples'):
                print(f'  {vid}: references changed; regenerate its samples (voice samples {vid}) and re-audition.')


# --- transcribe --------------------------------------------------------------------------------------------
def cmd_transcribe(args):
    vid = slugify(args.id)
    meta = load(vid)
    env = key_env(args)
    py = sys.executable
    work = WORK / vid  # review scratch (STT report, draft); the voice folder keeps only reference-N.wav/.txt
    work.mkdir(parents=True, exist_ok=True)
    for n, wav, _ in refs_of(vid):
        if args.ref and n != args.ref:
            continue
        subprocess.run([py, '-m', 'viettts.voices.transcription', str(wav)], check=True, env=env, cwd=ROOT)
        subprocess.run([py, '-m', 'viettts.voices.reconciliation', str(wav)], check=True, env=env, cwd=ROOT)
        report = json.loads(wav.with_suffix('.stt.json').read_text(encoding='utf-8'))
        shutil.move(str(wav.with_suffix('.stt.json')), str(work / f'stt-{n}.json'))
        draft = report.get('chosen') or report.get('consensus', '')
        (work / f'reference-{n}.draft.txt').write_text(draft + '\n', encoding='utf-8')
        ref = next(r for r in meta['references'] if r['n'] == n)
        ref['transcript_reviewed'] = False
        words = len(draft.split())
        print(f'\nreference-{n} draft ({words} words, {words / ref["duration"]:.1f} words/s): {draft}')
    meta['transcript_reviewed'] = False
    save(meta)
    print(
        f'\nReview each draft against {(work / "stt-N.json").relative_to(ROOT)} (all models + judges), then for each N:\n'
        f'  python3 -m viettts voice set-transcript {vid} --ref N --text "<final transcript>"'
    )


def cmd_set_transcript(args):
    vid = slugify(args.id)
    meta = load(vid)
    refs = meta.get('references', [])
    n = args.ref or (refs[0]['n'] if len(refs) == 1 else None)
    ref = next((r for r in refs if r['n'] == n), None)
    if not ref:
        raise SystemExit(f'Give --ref N (references: {[r["n"] for r in refs]}).')
    text = args.text or (Path(args.file).read_text(encoding='utf-8') if args.file else '')
    text = ' '.join(text.split())
    if not text:
        raise SystemExit('Give --text or --file.')
    (voice_dir(vid) / f'reference-{n}.txt').write_text(text + '\n', encoding='utf-8')
    rate = len(text.split()) / ref['duration']
    ref.update(transcript_reviewed=True, words_per_s=round(rate, 2))
    meta['transcript_reviewed'] = all(r.get('transcript_reviewed') for r in refs)
    if sum(len(t.read_text(encoding='utf-8')) for _, _, t in refs_of(vid) if t.is_file()) > 1024:
        print('  warning: transcripts exceed 1024 characters together (Drama-3 MLX limit)')
    save(meta)
    print(f'reference-{n} transcript saved ({len(text.split())} words, {rate:.1f}/s).')
    if not 2.5 <= rate <= 6.5:
        print('  warning: spoken Vietnamese is about 3.5-5 words/s; is the transcript complete and exact?')
    left = [r['n'] for r in refs if not r.get('transcript_reviewed')]
    print(f'Still to review: references {left}' if left else f'Next: python3 -m viettts voice samples {vid}')


# --- samples -----------------------------------------------------------------------------------------------
def cmd_samples(args):
    """Generate the test lines for one or more voices in a single Drama-3 run (one model load)."""
    lines = args.line or SAMPLE_LINES
    jobs, voices = [], {}
    for raw in args.ids:
        vid = slugify(raw)
        meta = load(vid)
        if not meta.get('transcript_reviewed'):
            raise SystemExit(f'{vid}: set the reviewed transcript of every reference first (set-transcript).')
        voice = voice_refs(vid)
        (voice_dir(vid) / 'samples').mkdir(exist_ok=True)
        voices[vid] = meta
        for n, text in enumerate(lines, 1):
            jid = hashlib.sha1(f'{vid}|{n}|{text}|{json.dumps(voice, ensure_ascii=False)}'.encode()).hexdigest()
            jobs.append(dict(id=jid, text=text, voice=voice, vid=vid, n=n))
    WORK.mkdir(parents=True, exist_ok=True)
    stage = WORK / 'samples-stage'
    shutil.rmtree(stage, ignore_errors=True)
    stage.mkdir()
    jobs_path = stage / 'jobs.jsonl'
    jobs_path.write_text(''.join(json.dumps(j, ensure_ascii=False) + '\n' for j in jobs), encoding='utf-8')
    command, env = python_command(
        'drama3', '-m', 'viettts', 'audiobook', 'worker', 'drama3', str(jobs_path), str(stage), '--skip-failed'
    )
    print(f'Generating {len(jobs)} Drama-3 samples for {", ".join(voices)} (loads the ~30 GB model) ...', flush=True)
    process = subprocess.Popen(
        command, cwd=ROOT, env=env, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True, encoding='utf-8'
    )
    retries, current = {v: 0 for v in voices}, 0
    assert process.stdout is not None  # stdout=PIPE guarantees a readable stream.
    for line in process.stdout:
        print(line, end='', flush=True)
        done = re.match(r'\[drama3\] (\d+)/\d+ ', line)
        if done:
            current = int(done[1])
        elif re.search(r'rejected|silence; retrying', line) and current < len(jobs):
            retries[jobs[current]['vid']] += 1  # retries are printed before the chunk's progress line
    if process.wait():
        raise SystemExit('Drama-3 failed; see the output above.')
    results: dict[str, list[dict[str, Any]]] = {v: [] for v in voices}
    for job in jobs:
        out = voice_dir(job['vid']) / 'samples' / f'sample-{job["n"]}.wav'
        made = stage / f'{job["id"]}.wav'
        if not made.is_file():  # Drama-3 gave up on this line; that is evidence about the voice
            out.unlink(missing_ok=True)
            results[job['vid']].append(dict(file=None, text=job['text'], failed=True))
            continue
        made.replace(out)
        results[job['vid']].append(dict(file=str(out.relative_to(ROOT)), text=job['text'], **measure(out)))
    shutil.rmtree(stage, ignore_errors=True)
    for vid, meta in voices.items():
        meta.update(samples=results[vid], sample_retries=retries[vid], samples_model=drama3_revision())
        save(meta)
        print(f'\n{vid}: {len(results[vid])} samples, {retries[vid]} retries')
        for r in results[vid]:
            if r.get('failed'):
                print(f'  FAILED after 4 tries: {r["text"]}')
                continue
            flag = '  <- long pause' if r['longest_pause'] > 0.8 else ''
            print(f'  {r["file"]}  {r["duration"]:4.1f}s  pause {r["longest_pause"]:.2f}s{flag}')
    print(
        '\nAsk the user to listen, then: python3 -m viettts voice approve <id> --gender female --style ... --fits ...'
    )


# --- approve / list / notes ---------------------------------------------------------------------------------
def cmd_approve(args):
    vid = slugify(args.id)
    meta = load(vid)
    if not meta.get('transcript_reviewed') or not all(r.get('transcript_reviewed') for r in meta.get('references', [])):
        raise SystemExit('Not every reference transcript is reviewed yet.')
    good = [x for x in meta.get('samples', []) if not x.get('failed')]
    if (not good or len(good) < len(meta.get('samples', []))) and not args.no_samples and not args.accept_failed:
        raise SystemExit(
            f'Only {len(good)} of {len(meta.get("samples", []))} samples succeeded; regenerate, pick '
            f'another cut, or pass --accept-failed if the user approves anyway.'
        )
    for key in ('name', 'gender', 'style', 'accent', 'fits', 'contact'):
        if getattr(args, key):
            meta[key] = getattr(args, key)
    if meta.get('gender') not in ('female', 'male'):
        raise SystemExit('Pass --gender female|male.')
    meta.update(status='onboarded', approved=datetime.now().isoformat(timespec='seconds'))
    save(meta)
    write_table()
    print(f'Onboarded "{vid}". Use it in a cast: {{"voices": {{"female": "{vid}"}}}} (audiobook build --cast)')


def cmd_note(args):
    meta = load(slugify(args.id))
    meta.setdefault('notes', []).append(f'{datetime.now():%Y-%m-%d}: {args.text}')
    save(meta)
    write_table()
    print('Note added.')


